const assert = require('node:assert/strict');
const path = require('node:path');
const fs = require('node:fs');
const { chromium } = require('playwright');

(async () => {
    const browser = await chromium.launch({ channel: process.env.SUITE_BROWSER || 'msedge', headless: true });
    try {
        const page = await browser.newPage({ viewport: { width: 1500, height: 1120 }, offline: process.env.SUITE_TEST_OFFLINE === '1' });
        page.setDefaultTimeout(15000);
        const errors = [];
        page.on('pageerror', error => errors.push(error.message));
        await page.route('http://127.0.0.1:8765/**', route => route.abort());
        await page.goto(process.env.SUITE_TEST_URL || 'http://127.0.0.1:5173');
        await page.getByRole('heading', { name: 'Стрічка подій', exact: true }).waitFor();
        await page.evaluate(async () => localforage.setItem('document_journal_v1', { version: 1, tasks: [], ovt: [], positions: [{ id: 'legacy-orphan', name: 'Архівний запис', status: 'знята', date: '2026-01-01', docNumber: '', details: 'Синтетичний старий запис', reportedInPbd: false }], settings: {} }));
        await page.reload();
        await page.getByRole('button', { name: 'Статус позицій', exact: true }).click();
        const scope = page.locator('#document-journal');
        await scope.getByRole('heading', { name: 'Статус позицій', exact: true }).waitFor();
        const store = () => page.evaluate(() => localforage.getItem('document_journal_v1'));
        const cards = scope.getByTestId('document-action-cards');
        assert.equal(await cards.getByText('Подано в ПБД', { exact: true }).count(), 0);
        assert.equal(await cards.getByText('Зняття', { exact: true }).count(), 1);
        assert.equal(await cards.getByText('Знищення', { exact: true }).count(), 1);
        assert.equal(await scope.getByTestId('position-category-cards').getByRole('button').count(), 5);
        assert.equal(await scope.getByTestId('position-category-cards').getByText('ОВгП', { exact: true }).count(), 1);
        assert.equal(await scope.locator('[data-document-id=legacy-orphan]').getByText('Потребує звірки', { exact: false }).count(), 1);
        const dialog = page.getByRole('dialog');
        const pick = async id => { await dialog.getByRole('combobox', { name: 'Позиція з реєстру', exact: true }).click(); await dialog.locator(`[role="option"][data-position-id="${id}"]`).click(); };
        const open = async () => { await scope.getByRole('button', { name: 'Додати запис', exact: true }).click(); await dialog.getByLabel('Дата зміни', { exact: true }).waitFor(); };
        const close = () => dialog.getByRole('button', { name: 'Закрити вікно журналу', exact: true }).click();
        const save = () => dialog.getByRole('button', { name: 'Зберегти запис', exact: true }).click();
        await open();
        await dialog.getByLabel('Дата зміни', { exact: true }).fill('2026-02-01');
        await dialog.getByLabel('Документальна дія', { exact: true }).selectOption('переміщена');
        await dialog.getByLabel('Позиція з реєстру', { exact: true }).click();
        assert.equal(await dialog.getByRole('listbox').getByRole('option').count(), 0);
        await close();
        await open();
        await dialog.getByLabel('Дата зміни', { exact: true }).fill('2026-02-01');
        await dialog.getByLabel('Назва позиції', { exact: true }).fill('Архів А');
        await dialog.getByLabel('Категорія позиції', { exact: true }).selectOption('Інші');
        await save();
        assert.equal((await store()).positions.length, 1, 'Blank document number requires explicit acknowledgement');
        await dialog.getByRole('checkbox', { name: 'Очікую номер донесення — зберегти з нагадуванням', exact: true }).check();
        await save();
        await dialog.waitFor({ state: 'hidden' });
        const creation = (await store()).positions.find(row => row.status === 'виставлена');
        const positionId = creation.positionId;
        const creationRow = scope.locator(`[data-document-id="${creation.id}"]`);
        assert.ok((await creationRow.getAttribute('class')).includes('dj-missing-doc'));
        const addEvent = async (status, date, newName) => {
            await open();
            await dialog.getByLabel('Дата зміни', { exact: true }).fill(date);
            await dialog.getByLabel('Документальна дія', { exact: true }).selectOption(status);
            await pick(positionId);
            if (newName) await dialog.getByLabel('Нова назва позиції', { exact: true }).fill(newName);
            await dialog.getByLabel('№ Позатермінового донесення', { exact: true }).fill('ТЕСТ/' + date);
            await save(); await dialog.waitFor({ state: 'hidden' });
        };
        await addEvent('переміщена', '2026-02-02');
        await addEvent('перейменована', '2026-02-03', 'Архів Б');
        const renamed = (await store()).positions.find(row => row.status === 'перейменована');
        await scope.getByLabel('Дата від', { exact: true }).fill('2026-02-03');
        await scope.getByLabel('Дата до', { exact: true }).fill('2026-02-03');
        await scope.getByRole('button', { name: 'Історія позиції ' + renamed.id, exact: true }).click();
        assert.equal(await dialog.getByTestId('position-history').locator('ol > li').count(), 3, 'History ignores table period filter');
        await dialog.getByText('Архів А → Архів Б', { exact: false }).first().waitFor();
        fs.mkdirSync(path.join(__dirname, '../test-results'), { recursive: true });
        await dialog.screenshot({ path: path.join(__dirname, '../test-results/position-history.png') });
        await close();
        await scope.getByRole('button', { name: 'Скинути фільтри', exact: true }).click();
        await addEvent('знята', '2026-02-04');
        await open();
        await dialog.getByLabel('Дата зміни', { exact: true }).fill('2026-02-05');
        await dialog.getByLabel('Документальна дія', { exact: true }).selectOption('переміщена');
        await dialog.getByLabel('Позиція з реєстру', { exact: true }).click();
        assert.equal(await dialog.getByRole('listbox').getByRole('option').count(), 0, 'Closed entry cannot be selected');
        await close();
        await scope.getByRole('button', { name: 'Редагувати запис ' + creation.id, exact: true }).click();
        await dialog.getByLabel('Дата зміни', { exact: true }).fill('2026-02-06');
        await save();
        await dialog.getByRole('alert').waitFor();
        assert.equal((await store()).positions.find(row => row.id === creation.id).date, '2026-02-01');
        await close();
        await scope.getByRole('button', { name: 'Видалити запис ' + creation.id, exact: true }).click();
        await dialog.getByRole('button', { name: 'Підтвердити видалення', exact: true }).click();
        await dialog.getByText('Зміна порушить історію', { exact: false }).waitFor();
        assert.equal((await store()).positions.length, 5);
        await close();
        await scope.getByRole('button', { name: 'Редагувати запис ' + creation.id, exact: true }).click();
        await dialog.getByLabel('№ Позатермінового донесення', { exact: true }).fill('ТЕСТ/ОТРИМАНО');
        await save(); await dialog.waitFor({ state: 'hidden' });
        assert.ok(!(await creationRow.getAttribute('class')).includes('dj-missing-doc'), 'Entering a number clears the red reminder');
        const updated = await store();
        assert.equal(updated.positionAudit.length, 5);
        assert.equal(updated.positionAudit.at(-1).before.docNumber, '');
        assert.equal(updated.positionAudit.at(-1).after.docNumber, 'ТЕСТ/ОТРИМАНО');
        assert.equal(updated.positions.find(row => row.id === 'legacy-orphan').category, undefined, 'Old records are never rewritten during loading');
        await scope.getByRole('checkbox', { name: 'Лише без номера донесення', exact: true }).check();
        assert.equal(await scope.locator('tbody tr[data-document-id]').count(), 1);
        await page.getByRole('button', { name: 'Завдання', exact: true }).first().click();
        await page.getByRole('button', { name: 'Статус позицій', exact: true }).click();
        assert.equal(await scope.getByRole('checkbox', { name: 'Лише без номера донесення', exact: true }).isChecked(), true);
        await page.reload();
        await page.getByRole('button', { name: 'Статус позицій', exact: true }).click();
        assert.equal(await scope.getByRole('checkbox', { name: 'Лише без номера донесення', exact: true }).isChecked(), true);
        await scope.getByRole('button', { name: 'Скинути фільтри', exact: true }).click();
        await scope.getByRole('button', { name: 'Потребує звірки: 1', exact: true }).click();
        assert.equal(await scope.locator('tbody tr[data-document-id]').count(), 1);
        await scope.getByRole('button', { name: 'Скинути фільтри', exact: true }).click();
        // Full Excel round-trip preserves the explicit creation/rename chain.
        const downloading = page.waitForEvent('download');
        await scope.getByRole('button', { name: 'Експорт трьох вкладок', exact: true }).click();
        const workbook = require('xlsx').read(fs.readFileSync(await (await downloading).path()), { type: 'buffer' });
        const { D } = require('./suite-document-journal.cjs');
        const P = await import('../src/modules/documents/position-register.js');
        const parsed = D.readWorkbook(workbook, require('xlsx'));
        const roundTrip = D.merge(D.empty(), parsed.incoming);
        assert.equal(roundTrip.added, 5);
        assert.equal(P.buildPositionRegister(roundTrip.next.positions).issues.size, 1, 'Only the original historical orphan remains unresolved');
        assert.equal(P.buildPositionRegister(roundTrip.next.positions).entries[0].records.length, 4);
        await page.emulateMedia({ reducedMotion: 'reduce' });
        assert.equal(await scope.locator('[data-document-id=legacy-orphan]').evaluate(el => getComputedStyle(el).animationName), 'none');
        await page.screenshot({ path: path.join(__dirname, '../test-results/position-register.png') });
        assert.deepEqual(errors, []);
        console.log('PASS: position cards/categories, missing-number acknowledgement and reminder, form lifecycle guards, full history, audit, filters/reload, legacy preservation, Excel round-trip and reduced-motion accessibility');
    } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
