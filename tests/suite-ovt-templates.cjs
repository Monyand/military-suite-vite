const assert = require('node:assert/strict');
const XLSX = require('xlsx');
const { D } = require('./suite-document-journal.cjs');
const { createHarness } = require('./suite-backup-unit.cjs');
(async () => {
    const T = await import('../src/core/ovt-templates.js');
    const S = await import('../src/core/shared-dictionaries.js');
    const { prepareOvtDraft, ovtCellText } = await import('../src/modules/documents/ovt-form.js');
    const { buildOvtReport } = await import('../src/modules/documents/ovt-report.js');
    let templates = T.emptyOvtTemplates();
    templates = T.addOvtTemplateLines(templates, 'tasks', 'підвозу будівельних матеріалів\n ПІДВОЗУ БУДІВЕЛЬНИХ МАТЕРІАЛІВ ');
    assert.equal(templates.tasks.length, 1);
    templates = T.addOvtTemplateLines(templates, 'equipmentTypes', 'вантажний автомобіль');
    templates = T.addOvtTemplateLines(templates, 'consequences', 'був повністю знищений', { status: 'ЗНИЩЕНО' });
    templates = T.addOvtTemplateLines(templates, 'consequences', 'був пошкоджений', { status: 'ПОШКОДЖЕНО' });
    templates.consequences.push('старий нерозподілений наслідок');
    assert.deepEqual(T.ovtTemplateOptions(templates, 'consequences', { status: 'ЗНИЩЕНО' }), ['був повністю знищений']);
    assert.deepEqual(T.ovtTemplateOptions(templates, 'consequences', { status: 'ПОШКОДЖЕНО' }), ['був пошкоджений']);
    assert.throws(() => T.addOvtTemplateLines(templates, 'tasks', ''), /хоча б/);
    assert.throws(() => T.validateOvtTemplates({ ...templates, tasks: [''] }), /порожній/);
    assert.throws(() => T.addOvtTemplateLines(templates, 'consequences', 'text', { status: 'unknown' }), /статус/);
    const config = { ...S.emptyDictionaries(), ovtTemplates: templates };
    assert.equal(S.validateDictionaries(config), config);
    const legacyConfig = S.emptyDictionaries(); delete legacyConfig.ovtTemplates;
    assert.equal(S.validateDictionaries(legacyConfig), legacyConfig); assert.equal(legacyConfig.ovtTemplates, undefined);
    const legacyTemplates = { tasks: ['task'], routes: [], equipmentTypes: [{ name: 'old', subject: 'техніка' }], descriptions: [], consequences: ['legacy'] };
    const legacyRaw = JSON.stringify(legacyTemplates); T.validateOvtTemplates(legacyTemplates); assert.equal(JSON.stringify(legacyTemplates), legacyRaw);
    const row = { ...D.cleanRow('ovt', { date: '2026-09-17', time: '20:00', category: 'Транспорт', nomenclature: 'ГАЗ-3307', status: 'ЗНИЩЕНО', serialNumber: 'TEST-VIN', plateNumber: 'TEST-01', taskText: 'підвозу будівельних матеріалів', routeText: 'Тест-А—Тест-Б,', equipmentType: 'вантажний автомобіль', eventDescription: 'зазнав вогневого ураження.', consequence: 'був повністю знищений.', reportSubject: 'техніка', coordinates: '37U DQ 00000 00000', locationMode: 'route', identifierType: 'vin', registrationType: 'plate' }), id: 'ovt-new' };
    const expected = 'Доповідаю, що 17.09.2026 близько 20:00, під час виконання завдання з підвозу будівельних матеріалів, за маршрутом Тест-А—Тест-Б, вантажний автомобіль ГАЗ-3307 (VIN: TEST-VIN, в/н: TEST-01) зазнав вогневого ураження в районі координат: 37U DQ 00000 00000. Унаслідок події був повністю знищений.';
    const original = JSON.stringify(row);
    assert.equal(buildOvtReport(row), expected);
    assert.ok(buildOvtReport({ ...row, consequence: 'відновлення недоцільне' }).endsWith('Унаслідок події відновлення недоцільне.'), 'Conclusion contains only the supplied phrase, no equipment prefix');
    const selected = { ...row, locationMode: 'position', position: 'Архівна', factoryNumber: 'К-ТЕСТ', boardNumber: '000', identifierType: 'factory', registrationType: 'board' };
    const selectedText = buildOvtReport(selected);
    assert.ok(selectedText.includes('на позиції Архівна,'));
    assert.ok(!selectedText.includes('за маршрутом'));
    assert.ok(selectedText.includes('(заводський № К-ТЕСТ, бортовий № 000)'));
    assert.ok(!selectedText.includes('TEST-VIN'));
    assert.ok(buildOvtReport({ ...selected, identifierType: 'serial' }).includes('серійний № TEST-VIN'));
    assert.ok(buildOvtReport({ ...row, consequence: '', coordinates: '' }).includes('[НАСЛІДОК]'));
    assert.ok(buildOvtReport({ ...row, category: 'РЕБ' }).includes('Маршрут: Тест-А'));
    assert.equal(ovtCellText(selected, 'serialNumber'), 'Заводський номер: К-ТЕСТ');
    assert.equal(ovtCellText(row, 'position'), row.routeText);
    assert.equal(ovtCellText({ category: 'БпЛА', position: '', crewName: 'ТЗ Кент' }, 'position'), 'ТЗ Кент');
    assert.equal(ovtCellText(row, 'comment'), row.eventDescription);
    const learned = T.learnOvtTemplates(templates, row);
    assert.deepEqual(T.learnOvtTemplates(learned, row), learned, 'Learning is idempotent');
    assert.ok(learned.routes.some(entry => entry.name === row.routeText && !entry.status && entry.equipmentType === row.equipmentType));
    assert.deepEqual(T.ovtTemplateOptions(learned, 'routes', { ...row, status: 'ПОШКОДЖЕНО' }), [row.routeText]);
    assert.deepEqual(T.ovtTemplateOptions(learned, 'routes', { ...row, equipmentType: 'танк' }), []);
    assert.deepEqual(T.ovtTemplateOptions(learned, 'models', { ...row, status: 'ПОШКОДЖЕНО' }), [row.nomenclature]);
    assert.deepEqual(T.ovtTemplateOptions(learned, 'models', { ...row, equipmentType: 'НРК' }), []);
    for (const key of ['tasks', 'routes', 'descriptions', 'models']) {
        const oldStatusLists = { ...T.emptyOvtTemplates(), [key]: ['ЗНИЩЕНО', 'ПОШКОДЖЕНО'].map(status => ({ name: 'Спільна фраза', equipmentType: 'НРК', status })) };
        const raw = JSON.stringify(oldStatusLists), normalized = T.normalizeOvtTemplates(oldStatusLists);
        assert.equal(JSON.stringify(oldStatusLists), raw, 'No mutation during normalization');
        assert.equal(normalized[key].length, 1, 'Collapse obsolete per-status duplicates');
        assert.equal(normalized[key][0].status, undefined);
        for (const status of T.OVT_STATUSES) assert.deepEqual(T.ovtTemplateOptions(oldStatusLists, key, { equipmentType: 'НРК', status }), ['Спільна фраза']);
        assert.deepEqual(T.addOvtTemplateLines(normalized, key, 'Спільна фраза', { status: 'ЗНИЩЕНО', equipmentType: 'НРК' }), normalized);
    }
    const oldConfig = S.emptyDictionaries(); delete oldConfig.ovtTemplates.models;
    const historic = { ovt: [{ category: 'Транспорт', nomenclature: 'Історична модель', equipmentType: 'НРК' }, { category: 'РЕБ', nomenclature: 'Не транспорт' }], settings: { ovtDict: { 'Транспорт': ['Пікап', 'Позашляховик', 'Власна стара модель'] } } };
    const historicRaw = JSON.stringify(historic), seeded = S.prepareOvtDictionaries(oldConfig, historic);
    assert.deepEqual(seeded.ovtTemplates.models.map(T.ovtTemplateName), ['Історична модель', 'Власна стара модель']);
    assert.equal(JSON.stringify(historic), historicRaw);
    const removed = structuredClone(seeded); removed.ovtTemplates.models = [];
    assert.deepEqual(S.prepareOvtDictionaries(removed, historic).ovtTemplates.models, [], 'Deleted suggestions are not resurrected');
    assert.equal(oldConfig.ovtTemplates.models, undefined, 'Old backup remains untouched');
    assert.deepEqual(D.defaultOvtDict['Транспорт'], []);
    assert.ok(!JSON.stringify(learned).includes('TEST-VIN'));
    const uavLearned = T.learnOvtTemplates(templates, { ...row, category: 'БпЛА' });
    assert.ok(T.ovtTemplateOptions(uavLearned, 'models', { ...row, category: 'БпЛА' }).includes(row.nomenclature));
    assert.equal(JSON.stringify(row), original);
    const draft = prepareOvtDraft({ category: 'Транспорт', comment: 'Старий опис', factoryNumber: 'old factory', routeText: 'old route' });
    assert.equal(draft.identifierType, 'factory'); assert.equal(draft.locationMode, 'route'); assert.equal(draft.eventDescription, 'Старий опис');
    const old = Object.fromEntries(D.schemas.ovt.fields.slice(0, 11).map(([key]) => [key, row[key]])); old.id = 'old';
    const journal = { ...D.empty(), ovt: [old, row] };
    const before = JSON.stringify(journal); D.validate(journal); assert.equal(JSON.stringify(journal), before);
    assert.equal(D.merge({ ...D.empty(), ovt: [old] }, { ovt: [old] }).duplicates, 1);
    const book = XLSX.utils.book_new();
    XLSX.utils.book_append_sheet(book, XLSX.utils.aoa_to_sheet([D.schemas.ovt.fields.map(([, title]) => title), D.schemas.ovt.fields.map(([key]) => row[key])]), 'Втрати ОВТ');
    const imported = D.merge(D.empty(), D.readWorkbook(book, XLSX).incoming).next;
    assert.equal(buildOvtReport(imported.ovt[0]), expected, 'Selected switches survive Excel');
    const harness = createHarness();
    config.ovtTemplates = learned;
    harness.persistent.set('document_journal_v1', journal); harness.persistent.set(S.DICTIONARY_KEY, config);
    const snapshot = await harness.api.collect(), password = 'test-ovt-templates-password';
    const restored = await harness.api.decrypt(await harness.api.encrypt(snapshot, password), password);
    assert.deepEqual(restored.localforage[S.DICTIONARY_KEY], config);
    assert.deepEqual(restored.localforage.document_journal_v1, journal);
    const plan = S.planLabelReplacement(snapshot, config, ['units']);
    assert.deepEqual(plan.next.localforage.document_journal_v1, journal);
    assert.deepEqual(plan.next.localforage[S.DICTIONARY_KEY].ovtTemplates, learned);
    console.log('PASS: contextual templates/status separation, legacy preservation, learning/deduplication, identifiers/location, punctuation, Excel and AES round trips');
})().catch(error => { console.error(error); process.exitCode = 1; });
