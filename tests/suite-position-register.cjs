const assert = require('node:assert/strict');
const { D } = require('./suite-document-journal.cjs');
const { createHarness } = require('./suite-backup-unit.cjs');

(async () => {
    const P = await import('../src/modules/documents/position-register.js');
    const row = (id, status, date, extra = {}) => ({ ...D.cleanRow('positions', { name: 'Архів А', status, date, category: 'Інші', docNumber: 'ТЕСТ/' + id, ...extra }), id, createdAt: date + 'T09:00:00.000Z', updatedAt: date + 'T09:00:00.000Z' });
    const creation = row('a', 'виставлена', '2026-01-01', { positionId: 'a' });
    const moved = row('b', 'переміщена', '2026-01-02', { positionId: 'a' });
    const renamed = row('c', 'перейменована', '2026-01-03', { positionId: 'a', newName: 'Архів Б' });
    const removed = row('d', 'знята', '2026-01-04', { positionId: 'a', name: 'Архів Б' });
    const rows = [creation, moved, renamed, removed];
    const before = JSON.stringify(rows);
    const register = P.buildPositionRegister(rows);
    assert.equal(register.issues.size, 0);
    assert.equal(register.entries.length, 1);
    assert.deepEqual(register.entries[0].aliases, ['Архів А', 'Архів Б']);
    assert.equal(register.entries[0].status, 'знята');
    assert.equal(register.entries[0].records.length, 4);
    assert.equal(P.buildPositionRegister(rows, '2026-01-02').entries[0].name, 'Архів А');
    assert.deepEqual(P.eligiblePositions(rows, { date: '2026-01-05' }), []);
    assert.equal(P.eligiblePositions(rows, { date: '2026-01-02' }).length, 1);
    for (const status of ['переміщена', 'перейменована', 'знята', 'знищена', 'облаштовується']) {
        const orphan = row('orphan', status, '2025-12-01', { newName: 'Архів В' });
        assert.ok(P.positionChangeError([], [orphan], orphan.id), 'Non-creation action cannot create an entity: ' + status);
    }
    assert.ok(P.positionChangeError(rows, rows.filter(item => item.id !== 'a'), 'a'), 'Cannot delete a creation with dependent records');
    assert.ok(P.positionChangeError(rows, rows.map(item => item.id === 'a' ? { ...item, date: '2026-01-05' } : item), 'a'), 'Cannot move creation after dependent documents');
    const tooLate = row('late', 'переміщена', '2026-01-05', { positionId: 'a' });
    assert.ok(P.positionChangeError(rows, [...rows, tooLate], 'late'));
    const duplicate = row('duplicate', 'виставлена', '2026-01-02', { name: ' АРХІВ   А ' });
    assert.ok(P.positionChangeError(rows, [...rows, duplicate], 'duplicate'));
    const ambiguousEvent = row('ambiguous', 'переміщена', '2026-01-03');
    assert.equal(P.buildPositionRegister([creation, duplicate, ambiguousEvent]).links.has('ambiguous'), false, 'Do not guess a legacy link after conflicting creation records');
    const reused = row('new', 'виставлена', '2026-01-06', { name: 'Архів Б' });
    assert.equal(P.positionChangeError(rows, [...rows, reused], 'new'), '');
    assert.equal(P.buildPositionRegister([...rows, reused]).entries.length, 2, 'Same name after closure is a separate history');
    const collision = row('other', 'виставлена', '2026-01-01', { name: 'Архів Б' });
    assert.ok(P.positionChangeError([creation, collision], [creation, collision, renamed], 'c'));
    const emptyRename = { ...renamed, newName: '' };
    assert.ok(P.positionChangeError([creation], [creation, emptyRename], 'c'));
    const legacyCreation = { ...creation }; delete legacyCreation.positionId; delete legacyCreation.category; delete legacyCreation.newName;
    const legacyEvent = { ...moved, positionId: '' };
    assert.equal(P.buildPositionRegister([legacyCreation, legacyEvent]).links.get('b'), 'a');
    const sameDayLegacy = { ...legacyEvent, date: '2026-01-01', createdAt: '2026-01-10T09:00:00Z' };
    const backfilledCreation = { ...creation, createdAt: '2026-01-20T09:00:00Z' };
    assert.equal(P.eligiblePositions([sameDayLegacy, backfilledCreation], sameDayLegacy).length, 1);
    assert.equal(P.buildPositionRegister([sameDayLegacy, backfilledCreation]).issues.size, 1, 'Unlinked backfilled documents still require explicit review');
    assert.equal(P.positionChangeError([sameDayLegacy, backfilledCreation], [{ ...sameDayLegacy, positionId: 'a' }, backfilledCreation], 'b'), '', 'Explicit same-day link must not depend on when the clerk entered the creation');
    const orphan = row('legacy', 'знята', '2025-01-01');
    const fixedNumber = { ...orphan, docNumber: 'ТЕСТ/номер' };
    assert.equal(P.positionChangeError([orphan], [fixedNumber], 'legacy'), '', 'Permit clerical corrections without fabricating a missing creation');
    const empty = D.empty();
    const populated = { ...empty, positions: [legacyCreation, legacyEvent, orphan] };
    assert.equal(D.validate(populated), populated);
    const audited = P.withPositionAudit(empty, populated, '2026-09-20T10:00:00Z');
    assert.equal(audited.positionAudit.length, 3);
    const corrected = P.withPositionAudit(audited, { ...audited, positions: [legacyCreation, legacyEvent, fixedNumber] });
    assert.equal(corrected.positionAudit.at(-1).before.docNumber, orphan.docNumber);
    assert.equal(corrected.positionAudit.at(-1).after.docNumber, fixedNumber.docNumber);
    assert.equal(P.withPositionAudit(corrected, corrected).positionAudit.length, 4, 'Unrelated saves do not generate duplicate history');
    assert.equal(JSON.stringify(rows), before);
    const imported = D.merge(D.empty(), { positions: rows }).next;
    assert.equal(P.buildPositionRegister(imported.positions).issues.size, 0, 'Import retains explicit position IDs despite new document IDs');
    assert.equal(P.buildPositionRegister(imported.positions).entries.length, 1);
    assert.equal(D.merge(imported, { positions: rows }).added, 0);
    for (const text of ['', ' ', '—', '-', 'не вказано', 'очікується', 'Н/Д', 'б/н']) assert.equal(D.hasDoc({ docNumber: text }), false);
    assert.equal(D.hasDoc({ docNumber: 'ПТД-12/34' }), true);
    const h = createHarness();
    h.persistent.set(D.KEY, corrected);
    const packed = await h.api.encrypt(await h.api.collect(), 'test-position-password');
    const unpacked = await h.api.decrypt(packed, 'test-position-password');
    h.persistent.set(D.KEY, D.empty());
    await h.api.restore(unpacked, 'test-position-password');
    assert.deepEqual(h.persistent.get(D.KEY), corrected, 'Encrypted backup retains links and audit snapshots');
    console.log('PASS: documentary registry, stable links/renames, chronological validity, closed/duplicate guards, dependent deletion, legacy orphan preservation, audit trail, Excel merge and encrypted backup');
})().catch(error => { console.error(error); process.exitCode = 1; });
