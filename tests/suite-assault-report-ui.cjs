const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { chromium } = require('playwright');
const { fixture } = require('./suite-assault-report.cjs');

(async () => {
    const { buildAssaultReport } = await import('../src/modules/events/assault-report.js');
    const browser = await chromium.launch({ channel: process.env.SUITE_BROWSER || 'msedge', headless: true });
    try {
        const page = await browser.newPage({ viewport: { width: 1500, height: 1080 }, offline: process.env.SUITE_TEST_OFFLINE === '1' });
        page.setDefaultTimeout(15000);
        const errors = []; page.on('pageerror', error => errors.push(error.message));
        await page.route('http://127.0.0.1:8765/**', route => route.abort());
        await page.goto(process.env.SUITE_TEST_URL || 'http://127.0.0.1:5173');
        await page.getByRole('heading', { name: 'Стрічка подій', exact: true }).waitFor();
        const base = fixture();
        const records = [base, fixture({ id: 'with-losses', friendlyLosses: { count200: 2, count300: 1, countZBV: 3 }, enemyLosses: [{ count200: 4, count300: 5, count200Unconfirmed: 9, count200Discovered: 6 }] }), fixture({ id: 'unclosed', actionDetails: { ...base.actionDetails, endTime: '' } }), fixture({ id: 'other', types: ['Інші ураження'] })];
        await page.evaluate(async events => {
            await localforage.setItem('enemy_events_v2', events);
            await localforage.setItem('enemy_settings_v1', { weapons: ['Тест'], positions: ['Не підставляти замість документального місця'] });
        }, records);
        await page.reload(); await page.getByRole('heading', { name: 'Стрічка подій', exact: true }).waitFor();
        const enemy = page.locator('[data-suite-module=enemy]');
        const store = () => page.evaluate(async () => ({ events: await localforage.getItem('enemy_events_v2'), settings: await localforage.getItem('enemy_settings_v1'), documents: await localforage.getItem('document_journal_v1') }));
        const before = await store();
        assert.equal(await enemy.getByRole('button', { name: /^Доповідь ШД / }).count(), 3);
        assert.equal(await enemy.getByRole('button', { name: 'Доповідь ШД unclosed', exact: true }).isDisabled(), true);
        assert.equal(await enemy.getByRole('button', { name: 'Доповідь ШД other', exact: true }).count(), 0);
        await enemy.getByPlaceholder('Опис, позивний, зброя...', { exact: true }).fill('Синтетичний');
        await enemy.locator('input[type=date]:visible').nth(0).fill('2026-09-18');
        await enemy.locator('input[type=date]:visible').nth(1).fill('2026-09-18');
        const filters = () => enemy.locator('input:visible,select:visible').evaluateAll(elements => elements.filter(el => el.type !== 'file').map(el => ({ value: el.value, checked: el.checked })));
        const initialFilters = await filters();
        const open = id => enemy.getByRole('button', { name: 'Доповідь ШД ' + id, exact: true }).click();
        const dialog = page.getByRole('dialog', { name: 'Позатермінове донесення · ШД', exact: true });
        await open(base.id);
        const editor = dialog.getByLabel('Текст доповіді ШД', { exact: true });
        assert.equal(await editor.inputValue(), buildAssaultReport(base).text);
        await dialog.getByText('формулювання з вашого шаблону', { exact: false }).waitFor();
        await page.evaluate(() => { Object.defineProperty(navigator, 'clipboard', { configurable: true, value: { writeText: async text => { window.__reportCopiedText = text; } } }); });
        const edited = (await editor.inputValue()).replace('Позиція не втрачена.', 'Стан позиції уточнюється.');
        await editor.fill(edited);
        await dialog.getByRole('button', { name: 'Копіювати текст', exact: true }).click();
        await dialog.getByRole('status').filter({ hasText: 'Текст скопійовано' }).waitFor();
        assert.equal(await page.evaluate(() => window.__reportCopiedText), edited);
        assert.deepEqual(await store(), before, 'Report generation/edit/copy must never write event data or settings');
        await editor.press('Escape'); await dialog.waitFor({ state: 'hidden' });
        assert.equal(await page.evaluate(() => document.activeElement?.getAttribute('aria-label')), 'Доповідь ШД ' + base.id);
        assert.deepEqual(await filters(), initialFilters, 'Closing report preserves every event filter');
        await open('with-losses');
        const expected = buildAssaultReport(records[1]).text;
        assert.equal(await editor.inputValue(), expected);
        assert.ok(expected.includes("ЗНИЩЕНО – 19 (ДЕВ'ЯТНАДЦЯТЬ) В/СЛ ЗС рф, ПОРАНЕНО – 5 (П'ЯТЬ)"));
        await dialog.getByText('звичайні — 4; непідтверджені — 9; виявлені — 6', { exact: false }).waitFor();
        await dialog.getByRole('button', { name: 'Копіювати текст', exact: true }).click();
        await dialog.getByRole('status').filter({ hasText: 'Текст скопійовано' }).waitFor();
        assert.equal(await page.evaluate(() => window.__reportCopiedText), expected, 'Clipboard uses the combined total and its words');
        fs.mkdirSync(path.join(__dirname, '../test-results'), { recursive: true });
        await dialog.screenshot({ path: path.join(__dirname, '../test-results/assault-document-report.png') });
        await page.evaluate(() => { navigator.clipboard.writeText = async () => { throw new Error('Synthetic clipboard rejection'); }; });
        await dialog.getByRole('button', { name: 'Копіювати текст', exact: true }).click();
        await dialog.getByRole('status').filter({ hasText: 'Ctrl+C' }).waitFor();
        assert.deepEqual(await editor.evaluate(el => [el.selectionStart, el.selectionEnd]), [0, expected.length]);
        await dialog.getByRole('button', { name: 'Копіювати текст', exact: true }).focus();
        await page.keyboard.press('Tab');
        assert.equal(await page.evaluate(() => document.activeElement?.getAttribute('aria-label')), 'Закрити доповідь ШД', 'Focus remains inside report');
        await page.keyboard.press('Shift+Tab');
        assert.equal(await page.evaluate(() => document.activeElement?.textContent), 'Копіювати текст');
        await page.keyboard.press('n'); assert.equal(await page.getByText('Нова подія', { exact: true }).count(), 0, 'Background N shortcut is blocked');
        await page.setViewportSize({ width: 420, height: 840 });
        assert.equal(await dialog.evaluate(el => el.scrollWidth <= el.clientWidth + 1), true, 'Report fits narrow screens');
        await dialog.getByRole('button', { name: 'Закрити доповідь ШД', exact: true }).click();
        assert.deepEqual(await filters(), initialFilters);
        await page.setViewportSize({ width: 1500, height: 1080 });
        await open(base.id); assert.equal(await editor.inputValue(), buildAssaultReport(base).text, 'Reopening creates a fresh draft without changing the saved record');
        await dialog.getByRole('button', { name: 'Закрити', exact: true }).click();
        await page.reload(); await page.getByRole('heading', { name: 'Стрічка подій', exact: true }).waitFor();
        assert.deepEqual(await store(), before, 'No hidden persistence or PBD changes after reload');
        assert.deepEqual(errors, []);
        console.log('PASS: report buttons only on assault cards, completed guard, exact template, editable/copyable draft, clipboard fallback, preserved data/filters, focus/shortcuts, mobile layout and offline reload');
    } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
