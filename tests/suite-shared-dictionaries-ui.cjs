const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { chromium } = require('playwright');
const { createHarness } = require('./suite-backup-unit.cjs');

(async () => {
    const browser = await chromium.launch({ channel: process.env.SUITE_BROWSER || 'msedge', headless: true });
    try {
        const context = await browser.newContext({ viewport: { width: 1560, height: 1050 }, acceptDownloads: true, offline: process.env.SUITE_TEST_OFFLINE === '1' });
        await context.route('http://127.0.0.1:8765/**', route => route.abort());
        const page = await context.newPage();
        page.setDefaultTimeout(20000);
        const errors = []; page.on('pageerror', error => errors.push(error.message));
        const ready = () => Promise.race([
            page.getByRole('heading', { name: 'Стрічка подій', exact: true }).waitFor(),
            page.getByRole('button', { name: 'Створити Єдиний Бекап', exact: true }).waitFor()
        ]);
        const top = name => page.getByRole('button', { name, exact: true }).first().click();
        await page.goto(process.env.SUITE_TEST_URL || 'http://127.0.0.1:5173'); await ready();
        await top('Медична Евакуація'); await page.getByRole('button', { name: 'Створити запис', exact: true }).waitFor();
        await page.evaluate(async () => {
            await SuiteRuntime.drain();
            SuiteRuntime.freeze();
            const person = { id: 'dict-roster', fullName: 'Тестова Анкета Довідників', callsign: 'Макет', rank: 'Солдат', unit: 'тест-старий', status: 'ok', currentTask: 'піхота', deploymentStartTime: null };
            const medical = { id: 'dict-med', name: person.fullName, callsign: person.callsign, rank: 'Солдат', unit: person.unit };
            localStorage.setItem('tactical_personnel', JSON.stringify([person]));
            await localforage.setItem('med_soldiers_v3', [medical]);
            await localforage.setItem('med_episodes_v3', [{ id: 'dict-ep', soldierId: medical.id, date: '2026-01-02T11:00', lossType: 'Поранення (300)', severity: 'Легкий', cause: 'Інше', injuries: {}, evacStatus: 'Евакуйований', rank: medical.rank, unit: medical.unit, personnelSnapshot: { ...medical }, actualLoc: 'Лісосмуга Тест', docLoc: 'Архів Тест', notes: 'тест-старий не замінювати в коментарях' }]);
            const settings = await localforage.getItem('med_settings_v3');
            await localforage.setItem('med_settings_v3', { ...settings, units: [...settings.units, person.unit], sectors: ['Старе некласифіковане місце'] });
            await localforage.setItem('document_journal_v1', { version: 1, schemaRevision: 1, tasks: [], ovt: [], positions: [{ id: 'dict-doc', date: '2026-01-01', name: 'Архів Тест', status: 'виставлена', category: 'Інші', docNumber: 'ТЕСТ-1', details: '', reportedInPbd: false }], settings: {} });
        });
        await page.reload(); await ready();
        await top('Медична Евакуація');
        await page.getByRole('button', { name: 'Створити запис', exact: true }).click();
        await page.getByLabel('Підрозділ військовослужбовця', { exact: true }).selectOption('тест-старий');
        const form = page.locator('#med-app form').first();
        assert.ok((await page.locator('#med-document-locs option').evaluateAll(nodes => nodes.map(node => node.value))).includes('Архів Тест'));
        assert.ok(!(await page.locator('#med-actual-locs option').evaluateAll(nodes => nodes.map(node => node.value))).includes('Архів Тест'));
        await top('Спільні довідники');
        const dialog = page.getByRole('dialog', { name: 'Спільні довідники', exact: true });
        await dialog.getByLabel('Варіанти назв', { exact: true }).fill('тест-старий\nтест варіант');
        await dialog.getByLabel('Стандартна назва', { exact: true }).fill('Тестовий стандарт');
        await dialog.getByRole('button', { name: 'Додати правила', exact: true }).click();
        await dialog.getByRole('button', { name: 'Зберегти довідники', exact: true }).click();
        await dialog.getByRole('alert').filter({ hasText: 'Довідники збережено' }).waitFor();
        assert.equal(await page.evaluate(async () => (await localforage.getItem('med_soldiers_v3'))[0].unit), 'тест-старий', 'Saving vocabulary alone cannot rewrite records');
        await dialog.getByRole('button', { name: 'Закрити спільні довідники', exact: true }).click();
        assert.equal(await page.getByLabel('Підрозділ військовослужбовця', { exact: true }).inputValue(), 'тест-старий', 'Open draft retains its selected value');
        assert.equal(await page.getByLabel('Підрозділ військовослужбовця', { exact: true }).locator('option[value="Тестовий стандарт"]').count(), 1);
        await form.locator(':scope > div').first().getByRole('button').click();
        await top('Журнал О/С'); await page.locator('#nav-personnel').click();
        assert.equal(await page.locator('#unit-datalist option[value="Тестовий стандарт"]').count(), 1, 'Native personnel suggestions update');
        await top('Спільні довідники');
        await dialog.getByRole('button', { name: /^Звання/ }).click();
        await dialog.getByRole('button', { name: 'Список пар', exact: true }).click();
        await dialog.getByLabel('Пари назв', { exact: true }).fill('Солдат\tТестове звання');
        await dialog.getByRole('button', { name: 'Додати правила', exact: true }).click();
        await dialog.getByRole('button', { name: 'Перегляд усіх замін', exact: true }).click();
        const preview = dialog.getByTestId('dictionary-preview');
        await preview.getByRole('heading', { name: /Попередній перегляд: [1-9]/ }).waitFor();
        assert.ok((await preview.locator('tbody tr').count()) >= 8);
        fs.mkdirSync(path.join(__dirname, '../test-results'), { recursive: true });
        await dialog.screenshot({ path: path.join(__dirname, '../test-results/shared-dictionaries.png') });
        await page.setViewportSize({ width: 800, height: 900 });
        assert.ok(await dialog.evaluate(node => node.getBoundingClientRect().right <= innerWidth && node.scrollWidth <= node.clientWidth + 1), 'Dictionary window fits a smaller screen');
        await page.setViewportSize({ width: 1560, height: 1050 });
        const before = await page.evaluate(async () => ({ people: await localforage.getItem('med_soldiers_v3'), episodes: await localforage.getItem('med_episodes_v3'), journal: await localforage.getItem('document_journal_v1') }));
        const password = 'dictionary-test-password-2026';
        await preview.getByLabel('Пароль захисної копії довідників', { exact: true }).fill(password);
        await preview.getByLabel('Повтор пароля захисної копії довідників', { exact: true }).fill(password);
        await preview.getByRole('checkbox').check();
        const downloaded = page.waitForEvent('download');
        await preview.getByRole('button', { name: 'Створити захисну копію й застосувати', exact: true }).click();
        const download = await downloaded;
        const copy = JSON.parse(fs.readFileSync(await download.path(), 'utf8'));
        assert.equal(copy.cipher, 'AES-256-GCM'); assert.ok(!JSON.stringify(copy).includes('тест-старий'));
        const decrypted = await createHarness().api.decrypt(copy, password);
        assert.deepEqual(decrypted.localforage.med_soldiers_v3, before.people, 'Encrypted backup contains pre-change records');
        const after = await page.evaluate(async () => ({ people: await localforage.getItem('med_soldiers_v3'), episodes: await localforage.getItem('med_episodes_v3'), journal: await localforage.getItem('document_journal_v1'), dictionary: await localforage.getItem('document_dictionaries_v1'), recovery: await localforage.getItem('military_suite_recovery_v1'), roster: JSON.parse(localStorage.getItem('tactical_personnel')) }));
        assert.equal(after.people[0].unit, 'Тестовий стандарт'); assert.equal(after.people[0].rank, 'Тестове звання');
        assert.equal(after.episodes[0].unit, 'Тестовий стандарт'); assert.equal(after.episodes[0].personnelSnapshot.unit, 'Тестовий стандарт');
        assert.equal(after.roster[0].unit, 'Тестовий стандарт'); assert.equal(after.roster[0].status, 'ok');
        assert.equal(after.episodes[0].notes, before.episodes[0].notes); assert.deepEqual(after.journal, before.journal);
        assert.equal(after.dictionary.history.length, 1); assert.equal(after.recovery.cipher, 'AES-256-GCM');
        assert.equal(await page.locator('[data-suite-module]').count(), 0, 'All React writers unmounted after apply');
        await dialog.getByRole('button', { name: 'Перезавантажити програму', exact: true }).click(); await ready();
        assert.equal(await page.evaluate(async () => (await localforage.getItem('med_soldiers_v3'))[0].unit), 'Тестовий стандарт');
        // Verify the visible recovery workflow, including dictionaries and filters.
        await top('Відновити бекап');
        const restore = page.getByRole('dialog', { name: 'Відновлення єдиного бекапу', exact: true });
        await restore.getByRole('button', { name: 'Попередній стан', exact: true }).click();
        await restore.getByLabel('Пароль єдиного бекапу', { exact: true }).fill(password);
        await restore.getByRole('button', { name: 'Перевірити файл', exact: true }).click();
        await restore.getByRole('checkbox', { name: 'Я закрив інші вкладки та підтверджую заміну поточних даних', exact: true }).check();
        await restore.getByRole('button', { name: 'Відновити всі дані', exact: true }).click();
        await restore.getByRole('alert').filter({ hasText: 'Відновлення завершено' }).waitFor();
        assert.deepEqual(await page.evaluate(() => localforage.getItem('med_soldiers_v3')), before.people);
        assert.equal(await page.evaluate(async () => (await localforage.getItem('document_dictionaries_v1')).history.length), 0);
        assert.deepEqual(errors, []);
        console.log('PASS: dictionary UI, shared suggestions, separate location lists, preserved drafts, mass preview, AES recovery, reload, rollback UI and no browser errors');
    } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exit(1); });
